@pytestmark_docker
def test_compose_postgres_and_redis_are_private(rendered_compose_config):
    for svc_name in ("postgres", "redis"):
        svc = rendered_compose_config["services"][svc_name]
        assert "ports" not in svc or not svc["ports"]


@pytestmark_docker
def test_compose_only_required_secrets_mounted_per_service(rendered_compose_config):
    services = rendered_compose_config["services"]

    def secret_sources(service_name: str) -> set[str]:
        return {s["source"] for s in services[service_name].get("secrets", [])}

    assert secret_sources("postgres") == {"postgres_password"}
    assert secret_sources("redis") == {"redis_conf", "redis_password"}
    app_secrets = secret_sources("app")
    assert app_secrets == {
        "app_secret",
        "session_secret",
        "throttle_secret",
        "postgres_password",
        "redis_password",
        "anthropic_api_key",
    }
