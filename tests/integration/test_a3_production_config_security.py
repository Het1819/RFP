"""Fixed-behavior counterparts to test_a3_production_config_weaknesses.py,
plus the Compose-structural checks from spec section 12 ("Compose",
items 32-37). These assert the CURRENT (fixed) state of the repository.

Compose-rendering tests shell out to `docker compose config` and are
skipped if the Docker CLI is unavailable -- they need local secret files
generated by scripts/generate_local_prod_secrets.py, which they generate
into a throwaway temp copy of the secrets directory structure via the
`COMPOSE_PROJECT_DIR`-independent `secrets/` path relative to the repo, so
they do not depend on (or clobber) any secrets/ the developer already has.
"""

import json
import pathlib
import shutil
import subprocess

import pytest

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]


def _read(relative_path: str) -> str:
    return (REPO_ROOT / relative_path).read_text(encoding="utf-8")


def _docker_available() -> bool:
    return shutil.which("docker") is not None


# ---------------------------------------------------------------------------
# Fixed-behavior counterparts (static file content)
# ---------------------------------------------------------------------------


