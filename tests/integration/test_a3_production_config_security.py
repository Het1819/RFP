# ---------------------------------------------------------------------------
# Compose structural checks (require Docker CLI; skipped otherwise)
# ---------------------------------------------------------------------------

pytestmark_docker = pytest.mark.skipif(
    not _docker_available(), reason="Docker CLI not available"
)


@pytest.fixture(scope="module")
def rendered_compose_config():
    if not _docker_available():
        pytest.skip("Docker CLI not available")

    secrets_dir = REPO_ROOT / "secrets"
    created_files = []
    secrets_dir.mkdir(exist_ok=True)
    required_files = {
        "app_secret.txt": "test-app-secret-32-chars-minimum-xx",
        "session_secret.txt": "test-session-secret-32-chars-minimum",
        "throttle_secret.txt": "test-throttle-secret-32-chars-minimum",
        "postgres_password.txt": "test-postgres-password",
        "redis_password.txt": "test-redis-password",
        "redis.conf": "requirepass test-redis-password\nappendonly yes\n",
        "anthropic_api_key.txt": "sk-ant-test-key-not-real",
    }
    for name, content in required_files.items():
        path = secrets_dir / name
        if not path.exists():
            path.write_text(content + "\n", encoding="utf-8")
            created_files.append(path)

    try:
        result = subprocess.run(
            [
                "docker",
                "compose",
                "-f",
                "docker-compose.prod.yml",
                "config",
                "--format",
                "json",
            ],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=60,
        )
        assert result.returncode == 0, result.stderr
        yield json.loads(result.stdout)
    finally:
        for path in created_files:
            path.unlink(missing_ok=True)


